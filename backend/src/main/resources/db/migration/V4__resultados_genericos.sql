-- Resultados por escalas, validos para cualquier test (Weil produce una; otros tests produciran perfiles).
-- La validacion del rango de opciones pasa a la definicion de cada test: el limite de 1 a 8 era propio de Weil.
ALTER TABLE assessment_responses DROP CONSTRAINT ck_response_option;
ALTER TABLE assessment_responses ADD CONSTRAINT ck_response_option CHECK (selected_option >= 0);

CREATE TABLE assessment_results (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id      BIGINT       NOT NULL REFERENCES assessment_attempts (id) ON DELETE CASCADE,
    scoring_version VARCHAR(40)  NOT NULL,
    scales          TEXT         NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_result_attempt UNIQUE (attempt_id)
);

