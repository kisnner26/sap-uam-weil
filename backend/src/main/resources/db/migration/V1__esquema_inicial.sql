-- ---------------------------------------------------------------- usuarios
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(160)  NOT NULL,
    email           VARCHAR(160),
    password_hash   VARCHAR(256),                       -- bcrypt; NULL para usuarios Moodle
    cedula          VARCHAR(32),
    moodle_id       INTEGER,                            -- negativo = cuenta Moodle anonimizada
    picture_url     VARCHAR(512),
    career          VARCHAR(160),
    auth_provider   VARCHAR(16)   NOT NULL,             -- 'manual' | 'moodle'
    role            VARCHAR(16)   NOT NULL DEFAULT 'CLIENTE',
    active          BOOLEAN       NOT NULL DEFAULT TRUE,
    session_version BIGINT        NOT NULL DEFAULT 0,   -- subirla invalida todas las sesiones abiertas
    mfa_secret      VARCHAR(512),                       -- secreto TOTP cifrado (AES-GCM)
    mfa_enabled     BOOLEAN       NOT NULL DEFAULT FALSE,
    anonymized_at   TIMESTAMPTZ,
    created_at      TIMESTAMPTZ   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uk_users_email     UNIQUE (email),
    CONSTRAINT uk_users_moodle_id UNIQUE (moodle_id),
    CONSTRAINT ck_users_role      CHECK (role IN ('CLIENTE', 'STAFF', 'ADMIN')),
    CONSTRAINT ck_users_provider  CHECK (auth_provider IN ('manual', 'moodle')),
    CONSTRAINT ck_users_moodle    CHECK (auth_provider <> 'moodle' OR moodle_id IS NOT NULL),
    CONSTRAINT ck_users_manual    CHECK (auth_provider <> 'manual' OR password_hash IS NOT NULL)
);
CREATE INDEX ix_users_email_lower ON users (lower(email));
CREATE INDEX ix_users_role        ON users (role);

-- ---------------------------------------------------------------- convocatorias y habilitacion
CREATE TABLE exam_sessions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(160) NOT NULL,
    test_id            VARCHAR(80)  NOT NULL,
    opens_at           TIMESTAMPTZ  NOT NULL,
    closes_at          TIMESTAMPTZ  NOT NULL,
    time_limit_minutes INTEGER,
    instructions       VARCHAR(500),
    cancelled_at       TIMESTAMPTZ,
    created_by         BIGINT       NOT NULL,
    created_at         TIMESTAMPTZ  NOT NULL,
    updated_at         TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_session_window CHECK (closes_at > opens_at)
);
CREATE INDEX ix_sessions_test_opens ON exam_sessions (test_id, opens_at DESC);

CREATE TABLE exam_enrollments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id           BIGINT       NOT NULL REFERENCES exam_sessions (id),
    email                VARCHAR(160) NOT NULL,
    full_name            VARCHAR(160),
    extra_minutes        INTEGER      NOT NULL DEFAULT 0,
    note                 VARCHAR(300),
    norm_group           VARCHAR(8)   NOT NULL DEFAULT 'UN',
    participant_age      INTEGER,
    access_code_hash     VARCHAR(64)  NOT NULL,         -- SHA-256 del codigo; el codigo solo viaja por correo
    user_id              BIGINT REFERENCES users (id),
    claimed_at           TIMESTAMPTZ,
    status               VARCHAR(16)  NOT NULL DEFAULT 'ENABLED',
    reapplies_attempt_id BIGINT,
    reminder_sent_at     TIMESTAMPTZ,
    created_by           BIGINT       NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_enrollment_status CHECK (status IN ('ENABLED', 'REVOKED')),
    CONSTRAINT ck_enrollment_extra  CHECK (extra_minutes BETWEEN 0 AND 120),
    CONSTRAINT ck_enrollment_group  CHECK (norm_group IN ('7-16', 'AN', 'AD', 'UN'))
);
CREATE UNIQUE INDEX uk_enrollment_code  ON exam_enrollments (access_code_hash);
CREATE INDEX ix_enrollment_session      ON exam_enrollments (session_id);
CREATE INDEX ix_enrollment_user         ON exam_enrollments (user_id);
CREATE INDEX ix_enrollment_email        ON exam_enrollments (session_id, lower(email));

-- ---------------------------------------------------------------- intentos
CREATE TABLE assessment_attempts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES users (id),
    enrollment_id    BIGINT REFERENCES exam_enrollments (id),
    test_id          VARCHAR(80)  NOT NULL,
    test_version     INTEGER      NOT NULL,
    status           VARCHAR(24)  NOT NULL,
    lease_token      VARCHAR(64)  NOT NULL,
    lease_expires_at TIMESTAMPTZ  NOT NULL,
    started_at       TIMESTAMPTZ  NOT NULL,
    deadline_at      TIMESTAMPTZ  NOT NULL,
    updated_at       TIMESTAMPTZ  NOT NULL,
    submitted_at     TIMESTAMPTZ,
    auto_submitted   BOOLEAN      NOT NULL DEFAULT FALSE,
    direct_score     INTEGER,
    participant_age  INTEGER,
    norm_group       VARCHAR(8),
    invalidated_at   TIMESTAMPTZ,
    invalidated_by   BIGINT,
    invalid_reason   VARCHAR(500),
    reviewed_at      TIMESTAMPTZ,
    reviewed_by      BIGINT,
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_attempt_status CHECK (status IN ('IN_PROGRESS', 'SUBMITTED')),
    CONSTRAINT ck_attempt_invalid CHECK (invalidated_at IS NULL OR status = 'SUBMITTED')
);
CREATE INDEX ix_attempt_user_test ON assessment_attempts (user_id, test_id, status, started_at DESC);
CREATE INDEX ix_attempt_enrollment ON assessment_attempts (enrollment_id);
CREATE INDEX ix_attempt_submitted ON assessment_attempts (test_id, submitted_at DESC) WHERE status = 'SUBMITTED';
CREATE INDEX ix_attempt_deadline ON assessment_attempts (deadline_at) WHERE status = 'IN_PROGRESS';
-- Un aspirante no puede tener dos intentos abiertos del mismo test (lo garantiza la base, no solo el codigo).
CREATE UNIQUE INDEX uk_attempt_active ON assessment_attempts (user_id, test_id) WHERE status = 'IN_PROGRESS';
-- Una habilitacion permite un unico intento.
CREATE UNIQUE INDEX uk_attempt_enrollment ON assessment_attempts (enrollment_id) WHERE enrollment_id IS NOT NULL;

CREATE TABLE assessment_responses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id      BIGINT  NOT NULL REFERENCES assessment_attempts (id) ON DELETE CASCADE,
    item_index      INTEGER NOT NULL,
    selected_option INTEGER NOT NULL,
    CONSTRAINT uk_response_attempt_item UNIQUE (attempt_id, item_index),
    CONSTRAINT ck_response_item   CHECK (item_index >= 0),
    CONSTRAINT ck_response_option CHECK (selected_option BETWEEN 1 AND 8)
);

CREATE TABLE assessment_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id  BIGINT       NOT NULL REFERENCES assessment_attempts (id) ON DELETE CASCADE,
    type        VARCHAR(48)  NOT NULL,
    detail      VARCHAR(240),
    occurred_at TIMESTAMPTZ  NOT NULL
);
CREATE INDEX ix_event_attempt ON assessment_events (attempt_id);

-- ---------------------------------------------------------------- privacidad y correos
CREATE TABLE consent_records (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id),
    policy_version INTEGER     NOT NULL,
    notice_sha256  VARCHAR(64) NOT NULL,
    accepted_at    TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_consent_user_version UNIQUE (user_id, policy_version)
);

CREATE TABLE notification_outbox (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       VARCHAR(32)   NOT NULL,
    to_email   VARCHAR(160)  NOT NULL,
    subject    VARCHAR(200)  NOT NULL,
    body       VARCHAR(4000) NOT NULL,
    status     VARCHAR(16)   NOT NULL DEFAULT 'PENDING',
    attempts   INTEGER       NOT NULL DEFAULT 0,
    last_error VARCHAR(300),
    created_at TIMESTAMPTZ   NOT NULL,
    sent_at    TIMESTAMPTZ,
    CONSTRAINT ck_outbox_status CHECK (status IN ('PENDING', 'SENT', 'SIMULATED', 'FAILED'))
);
CREATE INDEX ix_outbox_status ON notification_outbox (status, created_at);
CREATE INDEX ix_outbox_email  ON notification_outbox (lower(to_email));

-- ---------------------------------------------------------------- seguridad y auditoria
CREATE TABLE audit_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT       NOT NULL,                  -- 0 = el sistema (tareas automaticas)
    actor_name  VARCHAR(160) NOT NULL,
    action      VARCHAR(64)  NOT NULL,
    target_type VARCHAR(48)  NOT NULL,
    target_id   VARCHAR(96),
    detail      VARCHAR(500),
    occurred_at TIMESTAMPTZ  NOT NULL
);
CREATE INDEX ix_audit_occurred ON audit_events (occurred_at DESC);
CREATE INDEX ix_audit_actor    ON audit_events (actor_id);

CREATE TABLE login_throttles (
    throttle_key      VARCHAR(200) PRIMARY KEY,
    attempt_count     INTEGER      NOT NULL,
    window_started_at TIMESTAMPTZ  NOT NULL,
    blocked_until     TIMESTAMPTZ,
    updated_at        TIMESTAMPTZ  NOT NULL,
    version           BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX ix_throttle_updated ON login_throttles (updated_at);
